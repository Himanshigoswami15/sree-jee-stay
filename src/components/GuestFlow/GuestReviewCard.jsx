import React, { useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { Star, ShieldCheck, ExternalLink, Smartphone, HeartHandshake, Award } from 'lucide-react';
import confetti from 'canvas-confetti';
import { motion } from 'framer-motion';
import { useFeedback } from '../../context/FeedbackContext';
import { generateReviewText } from '../../utils/reviewGenerator';
import { getActiveProviders } from '../../utils/providerRouter';
import { KeywordChips } from './KeywordChips';
import { AutoReviewEditor } from './AutoReviewEditor';
import { ThankYouCard } from './ThankYouCard';
import { copyToMobileClipboard } from '../../utils/clipboardHelper';

const RATING_LABELS = {
  5: '5 — Excellent',
  4: '4 — Very Good',
  3: '3 — Good',
  2: '2 — Fair',
  1: '1 — Poor',
};

export function GuestReviewCard() {
  const [searchParams] = useSearchParams();
  const roomParam = searchParams.get('room') || searchParams.get('table') || '';
  const guestParam = searchParams.get('guest') || '';

  const { settings, keywords, addFeedback, checkIsDuplicate } = useFeedback();

  const [rating, setRating] = useState(5);
  const [selectedTags, setSelectedTags] = useState([]);
  const [customNote, setCustomNote] = useState('');
  const [tone, setTone] = useState(settings?.tone || 'friendly');
  const [guestContact, setGuestContact] = useState('');
  const [roomNumber] = useState(roomParam);
  const [variationSeed, setVariationSeed] = useState(() => Math.random());
  const [submitted, setSubmitted] = useState(false);

  const hotelName = settings?.hotelName || settings?.name || 'Hotel & Hospitality';
  const logoUrl = settings?.logoUrl || '';
  const brandColor = settings?.themeColor || '#0F172A';
  const isHighRating = rating >= 4;
  const activeProviders = getActiveProviders(settings);
  const isDuplicate = checkIsDuplicate(guestContact);

  // Auto-generate review text
  const autoGeneratedReviewText = generateReviewText({
    rating,
    selectedTags,
    customNote: '',
    hotelName,
    tone,
    reviewLength: settings?.reviewLength || 'short',
    includeEmojis: settings?.includeEmojis !== false,
    keywordsList: keywords,
    variationSeed,
  });

  const reviewText = customNote !== '' ? customNote : autoGeneratedReviewText;

  const toggleTag = (tagId) => {
    setSelectedTags((prev) =>
      prev.includes(tagId) ? prev.filter((t) => t !== tagId) : [...prev, tagId]
    );
    setCustomNote('');
    setVariationSeed(Math.random());
  };

  const handleRefreshPhrasing = () => {
    setCustomNote('');
    setVariationSeed(Math.random());
  };

  const handlePostToProvider = async (provider) => {
    if (isDuplicate) return;

    // 1. Copy review text to clipboard
    await copyToMobileClipboard(reviewText);

    // 2. Submit feedback internally
    addFeedback({
      roomNumber: roomNumber || 'Guest',
      rating,
      tags: selectedTags,
      reviewText,
      guestContact,
      postedPublic: true,
    });

    // 3. Confetti for positive feedback
    if (isHighRating) {
      try {
        confetti({
          particleCount: 75,
          spread: 70,
          origin: { y: 0.6 },
        });
      } catch (e) {}
    }

    setSubmitted(true);

    // 4. Open destination provider link
    if (provider?.url) {
      window.open(provider.url, '_blank', 'noopener,noreferrer');
    }
  };

  const handleSubmitPrivateFeedback = async (e) => {
    if (e) e.preventDefault();
    if (isDuplicate) return;

    addFeedback({
      roomNumber: roomNumber || 'Guest',
      rating,
      tags: selectedTags,
      reviewText,
      guestContact,
      postedPublic: false,
    });

    setSubmitted(true);
  };

  if (submitted) {
    return (
      <ThankYouCard
        rating={rating}
        guestContact={guestContact}
        onReset={() => {
          setSubmitted(false);
          setRating(5);
          setSelectedTags([]);
          setCustomNote('');
        }}
      />
    );
  }

  return (
    <motion.div
      className="guest-portal-card"
      initial={{ opacity: 0, y: 10 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.25, ease: [0.16, 1, 0.3, 1] }}
    >
      {/* 1. HERO BRANDING & IDENTITY */}
      <div style={{ marginBottom: '1.25rem' }}>
        {logoUrl ? (
          <img
            src={logoUrl}
            alt={hotelName}
            className="guest-brand-logo"
          />
        ) : (
          <div
            className="guest-brand-monogram"
            style={{ background: brandColor }}
          >
            {hotelName.charAt(0).toUpperCase()}
          </div>
        )}

        <h1 style={{ fontSize: '1.35rem', fontWeight: 700, color: 'var(--slate-900)', margin: '0 0 0.35rem' }}>
          {hotelName}
        </h1>

        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', gap: '0.5rem', flexWrap: 'wrap' }}>
          <span className="saas-badge saas-badge-neutral" style={{ fontSize: '0.725rem' }}>
            <ShieldCheck size={13} color="var(--emerald-600)" />
            <span>Verified Guest Feedback</span>
          </span>

          {roomNumber && (
            <span className="saas-badge saas-badge-neutral" style={{ fontSize: '0.725rem' }}>
              <span>Room {roomNumber}</span>
            </span>
          )}
        </div>
      </div>

      {/* 2. REFINED 1–5 STAR RATING SELECTOR */}
      <div style={{ margin: '1.25rem 0' }}>
        <div style={{ fontSize: '0.875rem', fontWeight: 600, color: 'var(--slate-700)', marginBottom: '0.5rem' }}>
          How would you rate your overall experience?
        </div>

        <div className="star-rating-row">
          {[1, 2, 3, 4, 5].map((star) => {
            const isFilled = star <= rating;
            return (
              <button
                key={star}
                type="button"
                className="star-interactive-btn"
                onClick={() => {
                  setRating(star);
                  setSelectedTags([]);
                  setCustomNote('');
                  setVariationSeed(Math.random());
                }}
                aria-label={`Rate ${star} star`}
              >
                <Star
                  size={32}
                  color={isFilled ? 'var(--gold-500)' : 'var(--slate-200)'}
                  fill={isFilled ? 'var(--gold-500)' : 'transparent'}
                  strokeWidth={1.5}
                />
              </button>
            );
          })}
        </div>

        <div style={{ fontSize: '0.8125rem', fontWeight: 600, color: isHighRating ? 'var(--gold-700)' : 'var(--slate-600)', marginTop: '0.25rem' }}>
          {RATING_LABELS[rating] || '5 — Excellent'}
        </div>
      </div>

      {/* 3. HIGHLIGHT / KEYWORD SELECTION GRID */}
      <KeywordChips
        rating={rating}
        selectedTags={selectedTags}
        onToggleTag={toggleTag}
      />

      {/* 4. WRITTEN REVIEW SECTION */}
      <AutoReviewEditor
        rating={rating}
        reviewText={reviewText}
        onTextChange={(val) => setCustomNote(val)}
        onRefreshPhrasing={handleRefreshPhrasing}
      />

      {/* 5. GUEST IDENTIFIER / ANTI-DUPLICATE FIELD */}
      <div style={{ margin: '1rem 0', textAlign: 'left' }}>
        <label className="saas-label" style={{ marginBottom: '0.35rem' }}>
          <Smartphone size={14} color="var(--slate-500)" />
          <span>Phone or Room Number (Verification):</span>
        </label>
        <input
          type="text"
          className="saas-input"
          value={guestContact}
          onChange={(e) => setGuestContact(e.target.value)}
          placeholder="e.g. 9876543210 or Room 204"
          style={{
            borderColor: isDuplicate ? 'var(--rose-500)' : undefined,
            background: isDuplicate ? 'var(--rose-50)' : undefined,
          }}
        />
        {isDuplicate && (
          <div style={{ fontSize: '0.75rem', color: 'var(--rose-600)', fontWeight: 500, marginTop: '0.25rem' }}>
            A review has already been recorded for this identifier.
          </div>
        )}
      </div>

      {/* 6. SUBMISSION ACTIONS */}
      <div style={{ marginTop: '1.25rem', display: 'flex', flexDirection: 'column', gap: '0.625rem' }}>
        {isHighRating ? (
          <>
            {activeProviders.map((provider) => (
              <button
                key={provider.type}
                type="button"
                className="saas-btn saas-btn-primary"
                onClick={() => handlePostToProvider(provider)}
                disabled={isDuplicate}
                style={{
                  width: '100%',
                  height: '46px',
                  justifyContent: 'center',
                  fontSize: '0.9375rem',
                }}
              >
                <ExternalLink size={16} />
                <span>Post Review on {provider.name}</span>
              </button>
            ))}
            <div style={{ fontSize: '0.725rem', color: 'var(--slate-400)', fontWeight: 500 }}>
              Review text is automatically copied to your clipboard upon tapping.
            </div>
          </>
        ) : (
          <button
            type="button"
            className="saas-btn saas-btn-danger-solid"
            onClick={handleSubmitPrivateFeedback}
            disabled={isDuplicate}
            style={{
              width: '100%',
              height: '46px',
              justifyContent: 'center',
              fontSize: '0.9375rem',
            }}
          >
            <HeartHandshake size={16} />
            <span>Submit Feedback to Duty Manager</span>
          </button>
        )}
      </div>
    </motion.div>
  );
}
