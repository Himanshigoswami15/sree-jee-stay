import React, { useState } from 'react';
import { useSearchParams } from 'react-router-dom';
import { Star, ShieldCheck, HeartHandshake, ExternalLink, Smartphone, Award } from 'lucide-react';
import confetti from 'canvas-confetti';
import { motion } from 'framer-motion';
import { useFeedback } from '../../context/FeedbackContext';
import { generateReviewText } from '../../utils/reviewGenerator';
import { getActiveProviders } from '../../utils/providerRouter';
import { KeywordChips } from './KeywordChips';
import { AutoReviewEditor } from './AutoReviewEditor';
import { ThankYouCard } from './ThankYouCard';
import { copyToMobileClipboard } from '../../utils/clipboardHelper';

const SENTIMENT_CONFIG = {
  5: { label: 'Absolute Perfection! 🌟', color: '#15803D', bg: '#ECFDF5', border: '#A7F3D0' },
  4: { label: 'Great Experience! 😊', color: '#0369A1', bg: '#F0F9FF', border: '#BAE6FD' },
  3: { label: 'Okay / Average 😐', color: '#B45309', bg: '#FFFBEB', border: '#FDE68A' },
  2: { label: 'Needs Improvement 😕', color: '#BE123C', bg: '#FFF1F2', border: '#FECDD3' },
  1: { label: 'Unsatisfactory 😞', color: '#B91C1C', bg: '#FEF2F2', border: '#FCA5A5' },
};

export function GuestReviewCard() {
  const [searchParams] = useSearchParams();
  const roomParam = searchParams.get('room') || searchParams.get('table') || '';
  const guestParam = searchParams.get('guest') || '';

  const { settings, keywords, addFeedback, checkIsDuplicate } = useFeedback();

  const [rating, setRating] = useState(5);
  const [selectedTags, setSelectedTags] = useState([]);
  const [customNote, setCustomNote] = useState('');
  const [tone, setTone] = useState(settings?.tone || 'friendly');
  const [guestContact, setGuestContact] = useState('');
  const [roomNumber] = useState(roomParam);
  const [variationSeed, setVariationSeed] = useState(() => Math.random());

  const [submitted, setSubmitted] = useState(false);

  const primaryColor = settings?.themeColor || '#2563EB';
  const isHighRating = rating >= 4;
  const activeProviders = getActiveProviders(settings);
  const isDuplicate = checkIsDuplicate(guestContact);

  const currentSentiment = SENTIMENT_CONFIG[rating] || SENTIMENT_CONFIG[5];

  // Auto-generate review text
  const autoGeneratedReviewText = generateReviewText({
    rating,
    selectedTags,
    customNote: '',
    hotelName: settings?.hotelName || settings?.name || 'Hotel',
    tone,
    reviewLength: settings?.reviewLength || 'short',
    includeEmojis: settings?.includeEmojis !== false,
    mentionStaff: settings?.mentionStaff !== false,
    mentionCleanliness: settings?.mentionCleanliness !== false,
    mentionFood: settings?.mentionFood !== false,
    mentionLocation: settings?.mentionLocation !== false,
    keywordsList: keywords,
    variationSeed,
  });

  // Effective review text shown to user (custom edited or auto generated)
  const reviewText = customNote !== '' ? customNote : autoGeneratedReviewText;

  const toggleTag = (tagId) => {
    setSelectedTags((prev) =>
      prev.includes(tagId) ? prev.filter((t) => t !== tagId) : [...prev, tagId]
    );
    setCustomNote(''); // Reset custom override so new tags update the text
    setVariationSeed(Math.random());
  };

  const handleRefreshPhrasing = () => {
    setCustomNote(''); // Regenerate natural variation
    setVariationSeed(Math.random());
  };

  const handlePostToProvider = async (provider) => {
    if (isDuplicate) return;

    // 1. Copy review text to mobile clipboard synchronously
    await copyToMobileClipboard(reviewText);

    // 2. Submit feedback internally
    addFeedback({
      roomNumber: roomNumber || 'Guest',
      rating,
      tags: selectedTags,
      reviewText,
      guestContact,
      postedPublic: true,
    });

    // 3. Trigger confetti celebration for 4-5 stars
    if (isHighRating) {
      try {
        confetti({
          particleCount: 100,
          spread: 75,
          origin: { y: 0.6 },
        });
      } catch (e) {}
    }

    setSubmitted(true);

    // 4. Open destination review provider
    if (provider?.url) {
      console.log(`[GuestReviewCard Debug] hotelSlug: "${settings?.hotelSlug}", hotelId: "${settings?.hotelId}", googleReviewUrl before window.open: "${provider.url}"`);
      window.open(provider.url, '_blank', 'noopener,noreferrer');
    }
  };

  const handleSubmitPrivateFeedback = async (e) => {
    if (e) e.preventDefault();
    if (isDuplicate) return;

    addFeedback({
      roomNumber: roomNumber || 'Guest',
      rating,
      tags: selectedTags,
      reviewText,
      guestContact,
      postedPublic: false,
    });

    setSubmitted(true);
  };

  if (submitted) {
    return (
      <ThankYouCard
        rating={rating}
        guestContact={guestContact}
        onReset={() => {
          setSubmitted(false);
          setRating(5);
          setSelectedTags([]);
          setCustomNote('');
        }}
      />
    );
  }

  return (
    <motion.div
      className="guest-card"
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.3, ease: [0.16, 1, 0.3, 1] }}
      style={{
        maxWidth: '480px',
        width: '100%',
        margin: '1.5rem auto',
        background: '#ffffff',
        borderRadius: '18px',
        padding: '2rem 1.5rem',
        boxShadow: '0 8px 30px rgba(0, 0, 0, 0.05)',
        border: '1px solid #E5E7EB',
        textAlign: 'center',
        boxSizing: 'border-box',
        position: 'relative',
        overflow: 'hidden',
      }}
    >
      <div>
        {/* HERO BRANDING HEADER */}
        <div style={{ marginBottom: '1.5rem' }}>
          {settings?.logoUrl ? (
            <img
              src={settings.logoUrl}
              alt="Hotel Logo"
              style={{
                width: '72px',
                height: '72px',
                borderRadius: '50%',
                margin: '0 auto 1rem',
                objectFit: 'cover',
                border: '1px solid #E5E7EB',
                boxShadow: '0 2px 8px rgba(0, 0, 0, 0.04)',
              }}
            />
          ) : (
            <div
              style={{
                width: '72px',
                height: '72px',
                borderRadius: '50%',
                background: primaryColor,
                color: '#ffffff',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
                fontSize: '1.75rem',
                fontWeight: 700,
                margin: '0 auto 1rem',
                border: '1px solid #E5E7EB',
                boxShadow: '0 2px 8px rgba(0, 0, 0, 0.04)',
              }}
            >
              {(settings?.hotelName || settings?.name || 'Hotel')[0]}
            </div>
          )}

          {/* Hotel Name & Badges */}
          <h1 style={{ fontSize: '1.375rem', fontWeight: 700, color: '#111827', margin: '0 0 0.5rem', letterSpacing: '-0.02em' }}>
            {settings?.hotelName || settings?.name || 'Hotel'}
          </h1>

          <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', gap: '0.5rem', flexWrap: 'wrap', marginBottom: '0.75rem' }}>
            <span style={{ fontSize: '0.75rem', fontWeight: 600, color: '#166534', background: '#ECFDF5', padding: '0.25rem 0.65rem', borderRadius: '9999px', border: '1px solid #A7F3D0', display: 'inline-flex', alignItems: 'center', gap: '0.25rem' }}>
              <ShieldCheck size={13} /> Official Guest Review
            </span>

            <span style={{ fontSize: '0.75rem', fontWeight: 600, color: '#1E40AF', background: '#EFF6FF', padding: '0.25rem 0.65rem', borderRadius: '9999px', border: '1px solid #BFDBFE', display: 'inline-flex', alignItems: 'center', gap: '0.25rem' }}>
              <Award size={13} /> 4.9 ★ Exceptional
            </span>
          </div>

          {/* Optional Room Prefill Notice */}
          {roomNumber && (
            <div style={{ fontSize: '0.775rem', color: '#4B5563', fontWeight: 500, background: '#FAFAFB', padding: '0.4rem 0.75rem', borderRadius: '12px', border: '1px solid #E5E7EB', display: 'inline-flex', alignItems: 'center', gap: '0.35rem' }}>
              <span>🏨</span> Welcome {guestParam ? `${guestParam} (` : ''}Room {roomNumber}{guestParam ? ')' : ''}!
            </div>
          )}
        </div>

        {/* 5-STAR RATING SELECTOR */}
        <div style={{ marginBottom: '1.5rem' }}>
          <div style={{ fontSize: '0.9375rem', fontWeight: 600, color: '#111827', marginBottom: '0.75rem' }}>
            How was your stay experience?
          </div>

          <div style={{ display: 'flex', justifyContent: 'center', gap: '0.5rem', marginBottom: '0.75rem' }}>
            {[1, 2, 3, 4, 5].map((star) => {
              const isActive = star <= rating;
              return (
                <motion.button
                  key={star}
                  type="button"
                  whileHover={{ scale: 1.15 }}
                  whileTap={{ scale: 0.95 }}
                  onClick={() => {
                    setRating(star);
                    setSelectedTags([]);
                    setCustomNote('');
                    setVariationSeed(Math.random());
                  }}
                  style={{
                    background: 'transparent',
                    border: 'none',
                    cursor: 'pointer',
                    padding: '0.25rem',
                    borderRadius: '50%',
                    display: 'flex',
                    alignItems: 'center',
                    justifyContent: 'center',
                  }}
                >
                  <Star
                    size={38}
                    color={isActive ? '#F59E0B' : '#E5E7EB'}
                    fill={isActive ? '#F59E0B' : '#E5E7EB'}
                    style={{
                      transition: 'all 0.2s cubic-bezier(0.16, 1, 0.3, 1)',
                    }}
                  />
                </motion.button>
              );
            })}
          </div>

          {/* SENTIMENT MOOD BADGE */}
          <motion.div
            key={rating}
            initial={{ scale: 0.95, opacity: 0.8 }}
            animate={{ scale: 1, opacity: 1 }}
            transition={{ duration: 0.2 }}
            style={{
              display: 'inline-block',
              background: currentSentiment.bg,
              color: currentSentiment.color,
              border: `1px solid ${currentSentiment.border}`,
              padding: '0.4rem 0.85rem',
              borderRadius: '9999px',
              fontSize: '0.8125rem',
              fontWeight: 600,
            }}
          >
            {currentSentiment.label}
          </motion.div>
        </div>

        {/* KEYWORD TAG CHIPS */}
        <KeywordChips
          rating={rating}
          selectedTags={selectedTags}
          onToggleTag={toggleTag}
        />

        {/* AUTO-GENERATED AI REVIEW EDITOR */}
        <AutoReviewEditor
          rating={rating}
          reviewText={reviewText}
          onTextChange={(val) => setCustomNote(val)}
          onRefreshPhrasing={handleRefreshPhrasing}
          currentTone={tone}
          onChangeTone={(t) => {
            setTone(t);
            setCustomNote('');
            setVariationSeed(Math.random());
          }}
        />

        {/* PHONE / CUSTOMER ID VERIFICATION INPUT */}
        <div style={{ margin: '1.25rem 0 1rem 0', textAlign: 'left' }}>
          <label
            style={{
              fontSize: '0.8125rem',
              fontWeight: 600,
              color: '#374151',
              display: 'flex',
              alignItems: 'center',
              gap: '0.35rem',
              marginBottom: '0.4rem',
            }}
          >
            <Smartphone size={15} color={primaryColor} />
            <span>Phone / Room / Customer ID (Anti-Duplicate Check):</span>
          </label>
          <input
            type="text"
            className="form-input"
            value={guestContact}
            onChange={(e) => setGuestContact(e.target.value)}
            placeholder="e.g. 9876543210 or Room 204"
            style={{
              width: '100%',
              fontSize: '0.875rem',
              height: '44px',
              padding: '0 0.85rem',
              borderRadius: '12px',
              border: isDuplicate ? '1px solid #EF4444' : '1px solid #E5E7EB',
              background: isDuplicate ? '#FEF2F2' : '#FAFAFB',
              color: '#111827',
              boxSizing: 'border-box',
              outline: 'none',
              transition: 'all 0.2s ease',
            }}
          />
          {isDuplicate && (
            <div style={{ fontSize: '0.775rem', color: '#EF4444', fontWeight: 500, marginTop: '0.35rem' }}>
              ⚠️ A review has already been submitted for this Phone / ID.
            </div>
          )}
        </div>

        {/* ACTION BUTTONS / PLATFORM ROUTERS */}
        <div style={{ marginTop: '1.25rem', display: 'flex', flexDirection: 'column', gap: '0.75rem' }}>
          {isHighRating ? (
            <>
              {activeProviders.map((provider) => (
                <motion.button
                  key={provider.type}
                  type="button"
                  className="btn-primary-action"
                  whileHover={isDuplicate ? {} : { translateY: -1 }}
                  whileTap={isDuplicate ? {} : { scale: 0.98 }}
                  onClick={() => handlePostToProvider(provider)}
                  disabled={isDuplicate}
                  style={{
                    height: '48px',
                    padding: '0 1.5rem',
                    borderRadius: '14px',
                    fontSize: '0.9375rem',
                    fontWeight: 600,
                    background: primaryColor,
                    color: '#ffffff',
                    display: 'inline-flex',
                    alignItems: 'center',
                    justifyContent: 'center',
                    gap: '0.5rem',
                    border: 'none',
                    boxShadow: '0 1px 2px rgba(0, 0, 0, 0.05), 0 4px 12px rgba(37, 99, 235, 0.15)',
                    opacity: isDuplicate ? 0.6 : 1,
                    cursor: isDuplicate ? 'not-allowed' : 'pointer',
                    width: '100%',
                    letterSpacing: '-0.01em',
                  }}
                >
                  <ExternalLink size={18} />
                  <span>Post Review on {provider.name}</span>
                </motion.button>
              ))}

              <div style={{ fontSize: '0.75rem', color: '#6B7280', fontWeight: 500 }}>
                📋 Tapping above auto-copies your review text to your phone clipboard!
              </div>
            </>
          ) : (
            <motion.button
              type="button"
              className="btn-primary-action"
              whileHover={isDuplicate ? {} : { translateY: -1 }}
              whileTap={isDuplicate ? {} : { scale: 0.98 }}
              onClick={handleSubmitPrivateFeedback}
              disabled={isDuplicate}
              style={{
                height: '48px',
                padding: '0 1.5rem',
                borderRadius: '14px',
                fontSize: '0.9375rem',
                fontWeight: 600,
                background: '#EF4444',
                color: '#ffffff',
                display: 'inline-flex',
                alignItems: 'center',
                justifyContent: 'center',
                gap: '0.5rem',
                border: 'none',
                boxShadow: '0 1px 2px rgba(0, 0, 0, 0.05), 0 4px 12px rgba(239, 68, 68, 0.15)',
                opacity: isDuplicate ? 0.6 : 1,
                cursor: isDuplicate ? 'not-allowed' : 'pointer',
                width: '100%',
                letterSpacing: '-0.01em',
              }}
            >
              <HeartHandshake size={18} />
              <span>Submit Private Feedback to Duty Manager</span>
            </motion.button>
          )}
        </div>
      </div>
    </motion.div>
  );
}

